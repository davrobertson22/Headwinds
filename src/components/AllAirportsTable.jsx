export const ALL_AIRPORTS_PAGE_SIZE = 50;

// Airports the engine doesn't rate individually count as this (models/demand.js).
export const DEFAULT_GATEWAY_SCORE = 0.20;
/** Gateway score (0–1) and whether the airport is individually rated. */
export function gatewayScoreOf(code) {
  const s = AIRPORT_GATEWAY_SCORES[code];
  return s == null ? { score: DEFAULT_GATEWAY_SCORE, rated: false } : { score: s, rated: true };
}

// ── Market tables, each loaded once per page load ───────────────────────────
// One per demand model: a classic world sorts on classic markets, a v2 world on
// the v2 ones (engine utils/market.js "Demand model v2"). Both are generated by
// tools/generate-airport-markets.mjs.
const MARKET_TABLES = new Map();
const MARKET_PROMISES = new Map();
const MARKET_IMPORTS = {
  1: () => import('../data/airportMarkets.js'),
  2: () => import('../data/airportMarketsV2.js'),
  3: () => import('../data/airportMarketsV3.js'),
};
const tableVersion = (v) => (v === 2 || v === 3 ? v : 1);
/** Load a demand model's generated market table (resolves to { AIRPORT_MARKETS, GROWTH_BUCKETS }). */
export function loadAirportMarkets(demandModel) {
  const v = tableVersion(demandModel);
  if (MARKET_TABLES.has(v)) return Promise.resolve(MARKET_TABLES.get(v));
  if (!MARKET_PROMISES.has(v)) {
    MARKET_PROMISES.set(v, MARKET_IMPORTS[v]().then((m) => { MARKET_TABLES.set(v, m); return m; }));
  }
  return MARKET_PROMISES.get(v);
}

/**
 * Who flies where: { [code]: [{ id, name, isPlayer }] } for every airport any
 * airline serves. A route counts at every airport it calls at, so a multi-stop
 * rotation is listed at its stops, as on the airport screen.
 */
export function airlinesByAirport(state) {
  const out = new Map();
  const add = (code, airline) => {
    if (!code) return;
    let list = out.get(code);
    if (!list) out.set(code, list = []);
    if (!list.some(a => a.id === airline.id)) list.push(airline);
  };
  const me = { id: 'player', name: state.airlineName || 'You', isPlayer: true };
  for (const r of state.routes ?? []) for (const l of routeLegs(r)) { add(l.from, me); add(l.to, me); }
  for (const r of state.cargoRoutes ?? []) { add(r.origin, me); add(r.destination, me); }
  for (const c of state.competitors ?? []) {
    const airline = { id: c.id, name: c.name, isPlayer: false };
    for (const key of Object.keys(c.routes ?? {})) {
      const [a, b] = key.split('-');
      add(a, airline); add(b, airline);
    }
  }
  return out;
}

