// generate-airport-markets.mjs
// Writes packages/engine/src/data/airportMarkets.js: each airport's passenger and freight market,
// summed over every other airport (see packages/engine/src/utils/airportMarket.js for why and how).
// Run from the project root:  node tools/generate-airport-markets.mjs
// Re-run whenever src/data/airports.js, metros or the demand model change —
// tools/airport-markets-test.mjs fails when the table is stale.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { computeAirportMarkets, growthBuckets } from '../packages/engine/src/utils/airportMarket.js';
import { setDemandModel } from '../packages/engine/src/utils/market.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// One table per demand model (engine utils/market.js "Demand model v2"): classic
// worlds read airportMarkets.js, v2 worlds airportMarketsV2.js.
const TABLES = [
  { model: 1, file: 'airportMarkets.js', note: 'classic demand model (worlds without demandModel)' },
  { model: 2, file: 'airportMarketsV2.js', note: 'demand model v2 (worlds with tickConfig.demandModel === 2)' },
  { model: 3, file: 'airportMarketsV3.js', note: 'demand model v3 (worlds with tickConfig.demandModel === 3)' },
];

for (const { model, file, note } of TABLES) {
  const t0 = Date.now();
  setDemandModel(model);
  const OUT = path.join(ROOT, 'packages', 'engine', 'src', 'data', file);
  const buckets = growthBuckets();
  const rows = computeAirportMarkets(undefined, buckets);
  const codes = Object.keys(rows).sort();
  const lines = [
    '// GENERATED by tools/generate-airport-markets.mjs — do not hand-edit.',
    '// Re-run that script whenever airports, metros or the demand model change.',
    '// Row: [cargo tonnes/wk, passengers/wk to destinations in each GROWTH_BUCKETS rate…],',
    model === 1
      ? '// at base (start-of-game) demand. See packages/engine/src/utils/airportMarket.js.'
      : `// at base (start-of-game) demand, ${note}. See packages/engine/src/utils/airportMarket.js.`,
    '',
    `export const GROWTH_BUCKETS = ${JSON.stringify(buckets)};`,
    '',
    'export const AIRPORT_MARKETS = {',
    ...codes.map(c => `  ${/^[A-Z][A-Z0-9]*$/.test(c) ? c : JSON.stringify(c)}:${JSON.stringify(rows[c])},`),
    '};',
    '',
  ];
  writeFileSync(OUT, lines.join('\n'));
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${codes.length} airports, ${buckets.length} growth buckets, ${Date.now() - t0} ms`);
}
setDemandModel(1);
