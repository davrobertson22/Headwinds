#!/usr/bin/env node
// @not-a-test
// Generates apps/headwinds-web/api/_lib/brandMarks.mjs — the airline logo marks
// and the tail-fin silhouette as plain SVG strings, for the public world pages.
//
//   node --import ./tools/_register-loader.mjs tools/generate-brand-marks.mjs
//   node --import ./tools/_register-loader.mjs tools/generate-brand-marks.mjs --check
//
// Why generated: the public pages (/worlds, an airline's page, the share card)
// are rendered by Vercel functions as strings, with no React and no JSX. The
// logos and the fin live in React components (src/components/AirlineLogo.jsx,
// TailFin.jsx). Redrawing them by hand for the server would be a second set of
// artwork to keep in step — and the fin's shape took six attempts to get right.
// So the REAL components are rendered here, once, with sentinel colours, and the
// markup is stored with the colours as tokens:
//
//   {C}  the mark's accent colour          {G}  a unique id prefix
//   {A}  the tail design's accent colour   {F}  the fuselage colour (the "white" band)
//
// Re-run when a logo, the fin silhouette or a tail design changes;
// tools/worlds-pages-test.mjs fails (via --check) when the file is stale.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const ROOT = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = path.join(ROOT, 'apps/headwinds-web/api/_lib/brandMarks.mjs');

const { default: AirlineLogo, AIRLINE_LOGOS } = await import('../src/components/AirlineLogo.jsx');
const { default: TailFin, FIN_W, FIN_H, FIN_PATH, LOGO_FREE_DESIGNS } = await import('../src/components/TailFin.jsx');
const { TAIL_DESIGNS } = await import('../packages/engine/src/data/livery.js');

const C = '#0a0b0c', TAIL = '#010101', ACCENT = '#020202', FUSE = '#030303';
const all = (s, from, to) => s.split(from).join(to);
const inner = (svg) => svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');

// ── Logo marks: the bare mark (no tile), accent as {C} ───────────────────────
const marks = {};
for (const logo of AIRLINE_LOGOS) {
  let html = inner(renderToStaticMarkup(createElement(AirlineLogo, { id: logo.id, size: 40, accentColor: C, bgColor: 'none' })));
  // Any ids the mark defines for itself (gradients, clips) → a per-instance prefix.
  const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]);
  for (const id of ids) html = all(all(html, `id="${id}"`, `id="{G}${ids.indexOf(id)}"`), `url(#${id})`, `url(#{G}${ids.indexOf(id)})`);
  if (!html.includes(C)) throw new Error(`logo "${logo.id}" does not use its accent colour — the sentinel never appeared`);
  marks[logo.id] = all(html, C, '{C}');
}

// ── Tail designs: what TailFin draws over the tail colour, per design ────────
const designs = {};
for (const design of TAIL_DESIGNS) {
  const html = renderToStaticMarkup(createElement(TailFin, {
    livery: { tail: TAIL, cheatline: ACCENT, fuselage: FUSE, tailDesign: design, logoOnTail: false },
    logo: { id: 'compass' }, height: 100, idPrefix: 'gen',
  }));
  const m = html.match(new RegExp(`<rect x="0" y="0" width="${FIN_W}" height="${FIN_H}" fill="${TAIL}"></rect>(.*?)</g><path `, 's'));
  if (!m) throw new Error(`could not find the "${design}" design in TailFin's markup`);
  designs[design] = all(all(m[1], ACCENT, '{A}'), FUSE, '{F}');
}

// ── Where the logo sits on the fin (TailFin keeps LOGO private) ──────────────
const withMark = renderToStaticMarkup(createElement(TailFin, {
  livery: { tail: TAIL, cheatline: ACCENT, fuselage: FUSE, tailDesign: 'solid', logoOnTail: true },
  logo: { id: 'compass' }, height: 100, idPrefix: 'gen',
}));
const pos = withMark.match(/<g transform="translate\(([\d.-]+) ([\d.-]+)\)"><svg width="(\d+)"/);
if (!pos) throw new Error("could not find the logo's position in TailFin's markup");
const outline = withMark.match(/<path d="[^"]+" fill="none" stroke="([^"]+)" stroke-width="([\d.]+)"/);

const out = `// GENERATED by tools/generate-brand-marks.mjs — do not hand-edit.
// The airline logo marks and the tail fin, rendered from the real components
// (src/components/AirlineLogo.jsx, TailFin.jsx) with colours as tokens.
// Regenerate:  node --import ./tools/_register-loader.mjs tools/generate-brand-marks.mjs

/** logo id → the bare mark's SVG children on a 40×40 box. {C} accent, {G} id prefix. */
export const LOGO_MARKS = ${JSON.stringify(marks, null, 2)};

/** The fin: a ${FIN_W}×${FIN_H} box, nose to the right. */
export const FIN = ${JSON.stringify({
  w: FIN_W, h: FIN_H, path: FIN_PATH,
  logo: { x: Number(pos[1]), y: Number(pos[2]), size: Number(pos[3]) },
  outline: { stroke: outline?.[1] ?? 'rgba(0,0,0,.18)', width: Number(outline?.[2] ?? 6) },
  logoFree: [...LOGO_FREE_DESIGNS],
}, null, 2)};

/** tail design → what is painted over the tail colour. {A} accent, {F} fuselage. */
export const TAIL_DESIGN_MARKUP = ${JSON.stringify(designs, null, 2)};
`;

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== out) { console.error('brandMarks.mjs is stale — run: node --import ./tools/_register-loader.mjs tools/generate-brand-marks.mjs'); process.exit(1); }
  console.log('brandMarks.mjs is up to date');
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(ROOT, OUT)} — ${Object.keys(marks).length} logos, ${Object.keys(designs).length} tail designs`);
}
